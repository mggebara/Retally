library(haven); library(dplyr)
d <- read_dta("<repo>/benchmark/.cache/claude-code/montero-2022-cooperative-property-rights/independent/2026-11-07-a/mount/montero_2022_cooperative_property_rights/ehpm_incomemodule_wreform.dta")
d <- zap_labels(d)
print(summary(d$norm_dist)); print(summary(d$own_amt - 500 - d$norm_dist))
print(table(d$Above500, d$own_amt >= 500))
print(table(d$year, useNA="a")); print(table(d$survey_year, useNA="a"))
for (bw in c(300,150)) {
  s <- d %>% filter(abs(norm_dist) <= bw)
  cat("bw", bw, "n", nrow(s), "\n")
  for (cl in c("Expropretario_ISTA","own_amt","Total_Propretario","Total_Propretario2","match_id","ID","Reform_Coop_id","Hacienda_id","CODIGO","AREA_HECTAREA"))
    cat("  ", cl, length(unique(s[[cl]])), "\n")
  cat(" props match_id x year", nrow(distinct(s, match_id, year)), "\n")
  cat(" means: hh_income_pc", mean(s$hh_income_pc), "real", mean(s$hh_inc_pc_real), "inc", mean(s$hh_income), "\n")
  cat(" n<bw strict", sum(abs(d$norm_dist) < bw), "\n")
}
print(table(d$reform, d$Above500)); print(table(d$Coop_Member, d$reform))
print(quantile(d$hh_income_pc, c(0,.1,.25,.5,.75,.9,.99,1)))
