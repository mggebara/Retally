library(haven); library(dplyr)
d <- "<repo>/benchmark/.cache/claude-code/grier-2023-sugar-roll-call-voting/blind/2026-11-02-c/mount/grier_2023_sugar_roll_call_voting/"
a <- read_dta(paste0(d,"SugarReplicate.dta")); b <- read_dta(paste0(d,"SugarReplicate_iter1.dta")); c <- read_dta(paste0(d,"SugarReplicate_iter2.dta"))
cat("b NA rows:", sum(is.na(b$totalcont)), "\n"); print(as.data.frame(b[is.na(b$totalcont), c("cong","name","state","district","vote","both")]))
cat("a>=b:", mean(a$totalcont>=b$totalcont, na.rm=T), " b>=c:", mean(b$totalcont>=c$totalcont, na.rm=T), "\n")
print(tapply(b$totalcont, b$cong, sum, na.rm=T))
print(as.data.frame(a[a$id != a$state_no + a$district, c("cong","name","state","state_no","district","id")]))
v <- a %>% mutate(y = as.integer(vote=="Aye"))
g <- v %>% group_by(id) %>% summarise(n=n(), sw = n_distinct(y)>1, b=min(both), nvote=sum(!vote %in% c("Aye","No")))
cat("Aye-vs-otherwise: switching districts:", sum(g$sw), " both==1 switchers:", sum(g$sw & g$b==1, na.rm=T), "\n")
print(table(g$sw, g$nvote))
g2 <- v %>% group_by(state_no, district) %>% summarise(n=n(), sw = n_distinct(y)>1, b=min(both), .groups="drop")
cat("by state_no/district: n groups", nrow(g2), " switching:", sum(g2$sw), " both:", sum(g2$sw & g2$b==1, na.rm=T), "\n")
print(table(g2$n))
# both==1 consistency within id
print(v %>% group_by(id) %>% summarise(x=n_distinct(both)) %>% count(x))
# direction among both==1 switchers (Aye-or-otherwise)
w <- v %>% group_by(id) %>% filter(n_distinct(y)>1, all(both==1)) %>% arrange(id, cong) %>% summarise(dir=paste(y, collapse="->"), votes=paste(vote, collapse="->"))
print(table(w$dir)); print(table(w$votes))
w2 <- v %>% group_by(id) %>% filter(n_distinct(y)>1, !all(both==1)) %>% arrange(id, cong) %>% summarise(dir=paste(y, collapse="->"), votes=paste(vote, collapse="->"))
print(table(w2$dir)); print(table(w2$votes))
