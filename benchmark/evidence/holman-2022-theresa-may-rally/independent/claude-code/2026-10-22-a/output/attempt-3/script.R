suppressMessages({library(haven); library(dplyr)})
M <- "<repo>/benchmark/.cache/claude-code/holman-2022-theresa-may-rally/independent/2026-10-22-a/mount/holman_2022_theresa_may_rally"
# sample-size checks only (no estimation)
g <- as.data.frame(zap_labels(read_dta(file.path(M, "global_approval.dta"))))
print(attr(read_dta(file.path(M, "global_approval.dta"))$execrlc, "labels"))
g <- g[order(g$country_code, g$qtr), ]
L <- function(x, k = 1) ave(x, g$country_code, FUN = function(z) if (k > 0) c(rep(NA, k), head(z, -k)) else c(tail(z, k), rep(NA, -k)))
g$F_app <- L(g$lag_approval, -1)
g$L_k16 <- L(g$kill_16, 1)
g$L_fem <- L(g$female_pres, 1)
g$L_growth <- L(g$growth, 1); g$L_inf <- L(g$log_inflation, 1); g$L_rlc <- L(g$execrlc, 1); g$L_el <- L(g$election_qtr, 1)
cnt <- function(v) sum(complete.cases(g[, v]))
base <- c("female_pres", "growth", "log_inflation", "execrlc", "election_qtr", "kill_16")
cat("lag_approval + base:", cnt(c("lag_approval", base)), "\n")
cat("F_app + base:", cnt(c("F_app", base)), "\n")
cat("lag_approval + base + L_k16:", cnt(c("lag_approval", base, "L_k16")), "\n")
cat("lag_approval + all lagged regs:", cnt(c("lag_approval", "L_k16", "L_fem", "L_growth", "L_inf", "L_rlc", "L_el")), "\n")
cat("F_app + lagged regs:", cnt(c("F_app", "L_k16", "L_fem", "L_growth", "L_inf", "L_rlc", "L_el")), "\n")
cat("lag_approval + base, execrlc>0:", sum(complete.cases(g[, c("lag_approval", base)]) & g$execrlc %in% 1:3), "\n")
cat("lag_approval + base + rally_event_any2:", cnt(c("lag_approval", base, "rally_event_any2")), "\n")
ok <- complete.cases(g[, c("lag_approval", base)])
print(table(g$country[ok]))
print(tapply(g$qtr[ok], g$country[ok], range))
