suppressMessages({library(haven); library(dplyr); library(fixest)})
D <- "<repo>/benchmark/.cache/claude-code/holman-2022-theresa-may-rally/independent/2026-11-02-c/mount/holman_2022_theresa_may_rally"
g <- read_dta(file.path(D, "global_approval.dta")) %>% zap_labels() %>% arrange(country_code, qtr)
vars <- c("lag_approval","kill_16","female_pres","growth","log_inflation","execrlc","election_qtr")
cat("complete", sum(complete.cases(g[, vars])), "\n")
for (v in vars) cat(v, sum(is.na(g[[v]])), "\n")
cat("execrlc==0 among complete", sum(complete.cases(g[, vars]) & g$execrlc == 0), "\n")
cat("rally_event_any2 NA among complete", sum(complete.cases(g[, vars]) & is.na(g$rally_event_any2)), "\n")
g$cc <- complete.cases(g[, vars])
print(g %>% group_by(country) %>% summarise(n=n(), ncc=sum(cc), ex0=sum(execrlc==0, na.rm=T), minq=min(qtr), maxq=max(qtr), fem=sum(female_pres,na.rm=T), k16=sum(kill_16)) %>% as.data.frame())
m <- feols(lag_approval ~ kill_16*female_pres + growth + log_inflation + execrlc + election_qtr | country_code, g, notes=FALSE)
cat("R2", r2(m, "r2"), "\n")
m2 <- feols(lag_approval ~ kill_16*female_pres + growth + log_inflation + i(execrlc) + election_qtr | country_code, g, notes=FALSE)
print(coef(m2)); cat("R2", r2(m2, "r2"), "\n")
g0 <- g %>% mutate(execrlc = ifelse(execrlc == 0, NA, execrlc))
m3 <- feols(lag_approval ~ kill_16*female_pres + growth + log_inflation + execrlc + election_qtr | country_code, g0, notes=FALSE)
cat("ex0 NA N", nobs(m3), "\n"); print(coef(m3)); cat("R2", r2(m3, "r2"), "\n")
