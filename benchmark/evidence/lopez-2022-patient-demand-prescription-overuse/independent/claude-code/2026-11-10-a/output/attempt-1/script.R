suppressMessages({library(haven); library(dplyr)})
d <- read_dta("<repo>/benchmark/.cache/claude-code/lopez-2022-patient-demand-prescription-overuse/independent/2026-11-10-a/mount/lopez_2022_patient_demand_prescription_overuse/Lopez_Sautmann_Schaner_2020/Data/LSS_analysis_datasets_20201108.dta")
cat(dim(d), "\n")
nm <- names(d)
lab <- sapply(d, function(x) { l <- attr(x, "label"); if (is.null(l)) "" else l })
cls <- sapply(d, function(x) class(x)[1])
nmiss <- sapply(d, function(x) sum(is.na(x)))
for (i in seq_len(min(400, length(nm)))) cat(i, nm[i], cls[i], nmiss[i], lab[i], "\n")
pre <- sub("^([A-Za-z]+).*", "\\1", nm)
print(head(sort(table(pre), decreasing=TRUE), 60))
cat("CC vars:\n")
for (v in nm[grepl("^CC[0-9]+$", nm)]) cat(v, nmiss[v], lab[v], "\n")
cat("vars with x:", sum(grepl("x", nm)), "\n")
print(head(nm[grepl("x", nm)], 50))
for (v in c("records","malaria","patient","home","patient_voucher","doctor_voucher","date","cscomnum","cscomnum_OS","clinic","selected_home_survey")) if (v %in% nm) {cat("==",v,"\n"); print(summary(d[[v]])); print(head(table(d[[v]], useNA="a"),10))}
cat("remaining names (401+):\n")
cat(nm[401:length(nm)][!grepl("x", nm[401:length(nm)])], "\n")
