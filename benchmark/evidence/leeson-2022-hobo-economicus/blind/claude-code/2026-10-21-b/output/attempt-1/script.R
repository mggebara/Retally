# Exploratory run: check merges and data coverage. No RESULT lines.
suppressPackageStartupMessages({library(readr); library(dplyr); library(lubridate); library(readxl)})
base <- "<repo>/benchmark/.cache/claude-code/leeson-2022-hobo-economicus/blind/2026-10-21-b/mount/leeson_2022_hobo_economicus/3 replication package/replicate/replicate"
dd <- file.path(base, "data")
cb <- tryCatch(read_excel(file.path(base, "Codebook.xlsx")), error=function(e) NULL)
if (!is.null(cb)) print(as.data.frame(cb), right=FALSE)
visits <- read_csv(file.path(dd,"metrovisitslog.csv"), show_col_types=FALSE)
pass <- read_csv(file.path(dd,"passersby.csv"), show_col_types=FALSE)
fr <- read_csv(file.path(dd,"friendliness.csv"), show_col_types=FALSE)
rec <- read_csv(file.path(dd,"receipts.csv"), show_col_types=FALSE)
visits <- visits %>% mutate(d=mdy(date), month=month(d), year=year(d))
m <- visits %>% left_join(pass, by=c("metro","month","year"))
cat("visits:", nrow(visits), " merged rows:", nrow(m), " missing passersby:", sum(is.na(m$passersby)), "\n")
print(m %>% filter(is.na(passersby)))
print(table(visits$date))
cat("n distinct dates:", n_distinct(visits$date), "\n")
fr$nresp <- rowSums(fr[,paste0("passresp",1:5)])
print(table(fr$nresp, useNA="ifany"))
print(summary(rec))
cat("cash nonNA:", sum(!is.na(rec$cash)), " cash&inkind nonNA:", sum(!is.na(rec$cash)&!is.na(rec$inkind)), "\n")
print(table(rec$metro))
