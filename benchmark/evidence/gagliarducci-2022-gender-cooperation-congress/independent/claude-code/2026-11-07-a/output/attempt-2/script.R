suppressMessages({library(haven);library(dplyr)})
d <- read_dta("<repo>/benchmark/.cache/claude-code/gagliarducci-2022-gender-cooperation-congress/independent/2026-11-07-a/mount/gagliarducci_2022_gender_cooperation_congress/3 replication package/Data/AnalysisData/bills_analysis_101-111_replication.dta")
d <- zap_labels(d)
d <- d %>% group_by(v2, sponsor_state_abbrev, sponsor_district, sponsor_term_served) %>% mutate(nbills = n()) %>% ungroup()
d$pct2 <- 100*d$numb_cosponsors_opposite/(d$numb_cosponsors+1)
cat("pct vs pct2 compare\n"); print(summary(100*d$pct_cosponsors_opposite - d$pct2))
print(table(zero=d$numb_cosponsors==0, napct=is.na(d$pct_cosponsors_opposite), useNA="a"))
base <- c("numb_cosponsors","sponsor_female","v2")
spon <- c("sponsor_age","sponsor_tenure_run","comc","comr","black","sponsor_party","occ1","occ2","occ3","occ4","occ5","ivycoll","borninstate")
dist <- c("pct_black","pct_urban","pct_for_born","pct_age_over65","lninc","lnpop","lnarea","sponsor_state_icpsr")
bill <- c("minor","house_judiciary")
cc <- function(v) sum(complete.cases(d[,v]))
cat("base", cc(base), "\n+bill", cc(c(base,bill)), "\n+spon", cc(c(base,bill,spon)), "\n+dist", cc(c(base,bill,spon,dist)), "\n")
for (s in spon) cat(s, cc(c(base,bill,s)), "\n")
for (s in c("agestart","anycoll","dwnom1","MV1_democrat","lag_demshare1","DSpndPct","private")) cat(s, cc(c(base,bill,spon,dist,s)), "\n")
all <- complete.cases(d[,c(base,bill,spon,dist)])
cat("party in full sample\n"); print(table(d$sponsor_party[all]))
cat("pct nonmissing in full sample", sum(all & !is.na(d$pct_cosponsors_opposite)), "\n")
cat("pct >100 in full sample by party\n"); print(table(d$sponsor_party[all & d$pct_cosponsors_opposite>1]))
s <- d[all,]; cat("sponsor-congress clusters", nrow(unique(s[,c("v2","sponsor_state_abbrev","sponsor_district","sponsor_term_served")])), "\n")
cat("sponsor_name x v2 clusters", nrow(unique(s[,c("v2","sponsor_name")])), "\n")
cat("mixed in full\n"); print(table(s$mixed_gender_election, is.na(s$MV1_female), useNA="a"))
print(table(s$sponsor_female, s$MV1_female>0))
print(summary(abs(s$MV1_democrat)))
