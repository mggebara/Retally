# Exploratory run 12: endline bribe and midline visit variables (no estimates)
suppressPackageStartupMessages({library(haven); library(dplyr)})
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-c/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
options(width = 220, warn = -1)
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% zap_labels()
ra$tf <- ra$treatment; ra$tf[ra$a7 == 654] <- 2
e1 <- read_dta(file.path(B, "survey_data/endline_round1_noPII.dta"))
lab <- function(d, v) cat(v, ":", attr(d[[v]], "label", exact = TRUE), "\n")
for (v in c("bribe", "visited", "visits", "paid_self", "replacement", "treatment", "code", "treated_twice", "titling_respondent")) lab(e1, v)
e1 <- zap_labels(e1)
e1$t <- ra$tf[match(e1$a7, ra$a7)]
cat("e1 treatment vs t\n"); print(table(e1$treatment, e1$t, useNA="ifany"))
cat("bribe x t\n"); print(table(e1$bribe, e1$t, useNA="ifany"))
cat("bribe nonNA by visited/paid_self:\n"); print(table(bribe_na = is.na(e1$bribe), visited = e1$visited, useNA="ifany"))
print(table(bribe_na = is.na(e1$bribe), paid_self = e1$paid_self, useNA="ifany"))
cat("today range by bribe nonNA:\n"); print(tapply(as.Date(e1$today), !is.na(e1$bribe), range))
cat("dup code:", sum(duplicated(e1$code)), "\n")
cat("transport-like names:\n"); print(grep("transp|bribe|other_pay|informal|fee", names(e1), value = TRUE))
for (v in grep("^other|informal|pay_", names(e1), value = TRUE)[1:30]) if (!is.na(v)) cat(v, ":", substr(attr(read_dta(file.path(B, "survey_data/endline_round1_noPII.dta"), col_select = all_of(v), n_max = 1)[[v]], "label", exact=TRUE), 1, 100), "\n")
e2 <- read_dta(file.path(B, "survey_data/endline_round2_noPII.dta")) %>% zap_labels()
cat("round2 has bribe?", "bribe" %in% names(e2), "\n")
ec <- read_dta(file.path(B, "survey_data/endline_2016campaign_noPII.dta"))
for (v in intersect(c("bribe", "transport", "a7", "treatment", "code", "today", "visited", "visit"), names(ec))) lab(ec, v)
ec <- zap_labels(ec); cat("ec dim", dim(ec), "\n")
if ("a7" %in% names(ec)) { ec$t <- ra$tf[match(ec$a7, ra$a7)]; print(table(ec$bribe, ec$t, useNA = "ifany")) }
cat("ec code in e1 code:", mean(ec$code %in% e1$code), "\n")
if ("today" %in% names(ec)) print(range(as.Date(ec$today), na.rm=T))
mid <- read_dta(file.path(B, "survey_data/midline_noPII.dta"), col_select = c(a7, compound, visited, visits, pilot, tot_complete, present, today, dup_compound, dup_real, monitoring_survey_twice, unknown_compound, exempt, first_attempt))
for (v in c("visited", "visits", "present")) cat(v, ":", attr(mid[[v]], "label", exact = TRUE), "\n")
mid <- zap_labels(mid); mid$t <- ra$tf[match(mid$a7, ra$a7)]
m <- mid %>% filter(pilot == 0, t %in% 1:2)
cat("visited x visits (L+C):\n"); print(table(m$visited, pmin(m$visits, 10), useNA = "ifany"))
cat("tot_complete x visited NA:\n"); print(table(m$tot_complete, is.na(m$visited)))
cat("dup compound among L+C midline:", sum(duplicated(m$compound)), " complete dups:", sum(duplicated(m$compound[m$tot_complete==1])), "\n")
cat("dup_compound:"); print(table(m$dup_compound, useNA="ifany")); cat("first_attempt:"); print(table(m$first_attempt, useNA="ifany"))
