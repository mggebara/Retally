# Exploratory: sensitivity of compliance coding to payment-record filters (no RESULT lines)
suppressMessages({library(haven); library(dplyr); library(fixest); library(lubridate)})
options(width = 200)
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-b/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
tb <- function(...) print(table(..., useNA = "ifany"))
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% transmute(a7, treatment = as.vector(treatment), stratum)
ra$treatment[ra$a7 == 654] <- 2
rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"), col_select = c(start, a7, house, compound1, exempt))
reg <- rg %>% inner_join(ra, by = "a7") %>% mutate(house = as.vector(house), rdate = as.Date(start)) %>%
  filter(house %in% c(1, 2)) %>% arrange(compound1, start) %>% distinct(compound1, .keep_all = TRUE)
pay <- read_dta(file.path(B, "admin_data/tax_payments_noPII.dta")) %>% mutate(paidm = as.vector(paid))
pay <- pay %>% left_join(reg %>% select(compound1, ra7 = a7, treatment, rdate), by = "compound1")
cat("lateCollection: date vs endOfCollect\n"); print(pay %>% group_by(lateCollection) %>% summarise(n = n(), late_by = mean(date > endOfCollect, na.rm=TRUE), dmin = min(date, na.rm=TRUE), dmax = max(date, na.rm=TRUE)))
cat("by arm: late, error_code, unmatched, paid merge\n")
tb(pay$treatment, pay$lateCollection); tb(pay$treatment, pay$error_code); tb(pay$treatment, pay$unmatched_compound); tb(pay$treatment, pay$paidm)
cat("endOfCollect - rdate (days) by arm\n"); print(pay %>% filter(treatment %in% 1:3) %>% group_by(treatment) %>% summarise(q = paste(quantile(as.numeric(endOfCollect - rdate), c(.05,.5,.95), na.rm=TRUE), collapse=" ")))
cl0 <- reg %>% filter(treatment %in% c(1, 2)) %>% mutate(local = as.integer(treatment == 2))
s <- as.Date("2018-06-19"); e <- as.Date("2018-12-11")
bounds <- s %m+% months(seq(0, 24, by = 2))
cl0 <- cl0 %>% mutate(period = findInterval(as.numeric(rdate), as.numeric(bounds)), inwin = rdate >= s & rdate <= e)
variant <- function(p, label) {
  ids <- unique(p$compound1)
  d <- cl0 %>% mutate(paid = as.integer(compound1 %in% ids))
  a <- feols(paid ~ local | stratum, d, cluster = ~a7); b <- feols(paid ~ local | stratum + period, d %>% filter(inwin), cluster = ~a7)
  cat(sprintf("%-28s C=%.4f L=%.4f | col1 %.4f col2 %.4f | Cw=%.4f\n", label, mean(d$paid[d$local==0]), mean(d$paid[d$local==1]), coef(a)[1], coef(b)[1], mean(d$paid[d$local==0 & d$inwin])))
}
variant(pay, "all")
variant(pay %>% filter(!(lateCollection %in% 1)), "no late")
variant(pay %>% filter(!(error_code %in% 1)), "no error_code")
variant(pay %>% filter(!(unmatched_compound %in% 1)), "no unmatched")
variant(pay %>% filter(paidm %in% 1), "paid merge==1")
variant(pay %>% filter(!is.na(date) & date <= as.Date("2018-12-31")), "date<=2018")
variant(pay %>% filter(a7 == ra7), "pay a7==reg a7")
variant(pay %>% filter(!is.na(date) & date >= rdate), "date>=reg date")
variant(pay %>% filter(!(lateCollection %in% 1) & !(error_code %in% 1)), "no late, no err")
