# Exploratory: sample construction counts, survey variable names (no estimates)
suppressMessages({library(haven); library(dplyr)})
options(width = 220)
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-b/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
tb <- function(...) print(table(..., useNA = "ifany"))
rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"),
  col_select = c(today, a7, tmt, carto_pay, house, compound1, compound2, exempt, collect_success, amt_paid, tot_complete, double_sensi, dup_poly, pilot, time, month_tmp_fr))
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% select(a7, treatment, stratum) %>% mutate(treatment = as.vector(treatment))
rs <- read_dta(file.path(B, "admin_data/randomization_schedule.dta")) %>% select(a7, month)
cat("month_tmp_fr:\n"); tb(rg$month_tmp_fr)
cat("time head:\n"); print(head(rg$time, 20))
r <- rg %>% inner_join(ra, by = "a7") %>% left_join(rs, by = "a7")
cat("rows in 356 nbhds:", nrow(r), " nbhds:", n_distinct(r$a7), "\n")
tb(r$treatment); tb(r$pilot); tb(as.vector(r$house)); tb(r$tot_complete); tb(r$double_sensi)
r2 <- r %>% filter(as.vector(house) != 3)
cat("non-villa by treatment\n"); tb(r2$treatment)
cat("dup compound1 within non-villa:", sum(duplicated(r2$compound1)), "\n")
r3 <- r2 %>% distinct(compound1, .keep_all = TRUE)
tb(r3$treatment)
r4 <- r2 %>% filter(tot_complete == 1)
cat("tot_complete==1:\n"); tb(r4$treatment)
cat("double_sensi==0 & tot_complete:\n"); tb(r4$treatment[r4$double_sensi == 0])
cat("missing today by treatment:\n"); tb(r2$treatment, is.na(r2$today))
cat("missing today by a7 (C/L):\n"); print(r2 %>% filter(treatment %in% c(1,2)) %>% group_by(a7, treatment, month) %>% summarise(n = n(), nmiss = sum(is.na(today)), .groups="drop") %>% filter(nmiss > 0) %>% as.data.frame())
cat("all nbhd counts (non-villa):\n")
nb <- r2 %>% group_by(a7, treatment, month) %>% summarise(n = n(), d0 = suppressWarnings(min(today, na.rm=TRUE)), dmed = median(today, na.rm=TRUE), .groups = "drop")
print(nb %>% group_by(treatment, month) %>% summarise(k = n(), n = sum(n), d0min = min(d0), d0max = max(d0), .groups="drop") %>% as.data.frame())
# payments
pay <- read_dta(file.path(B, "admin_data/tax_payments_noPII.dta"))
pay <- pay %>% mutate(in_reg = compound1 %in% r2$compound1)
cat("payments in reg:\n"); tb(pay$in_reg)
print(pay %>% filter(amountCF > 20000 | amountCF < 1000 | is.na(amountCF)) %>% select(compound1, a7, amountCF, date, house, paid, error_code) %>% as.data.frame())
cat("payment a7 vs compound a7 mismatch:", sum(pay$a7 != floor(pay$compound1/1000), na.rm=TRUE), "\n")
pp <- pay %>% left_join(r3 %>% select(compound1, rtreat = treatment, rmonth = month, today), by = "compound1")
cat("payment date - reg date by arm-month (days):\n")
print(pp %>% filter(!is.na(rtreat)) %>% group_by(rtreat, rmonth) %>% summarise(n = n(), q10 = quantile(as.numeric(date - today), .1, na.rm=TRUE), q50 = median(as.numeric(date - today), na.rm=TRUE), q90 = quantile(as.numeric(date - today), .9, na.rm=TRUE), dmin = min(date, na.rm=TRUE), dmax = max(date, na.rm=TRUE), .groups="drop") %>% as.data.frame())
cat("paid var x error_code\n"); tb(as.vector(pay$paid), pay$error_code)
# survey variable names
for (f in c("survey_data/midline_noPII.dta", "survey_data/endline_round1_noPII.dta", "survey_data/endline_round2_noPII.dta", "survey_data/baseline_noPII.dta")) {
  d <- read_dta(file.path(B, f), n_max = 0)
  labs <- sapply(d, function(x) { l <- attr(x, "label"); if (is.null(l)) "" else l })
  cat("\n=====", f, ncol(d), "\n")
  keep <- if (f == "survey_data/midline_noPII.dta") rep(TRUE, ncol(d)) else grepl("a7|compound|code|transport|bribe|visit|treat|tmt|stratum|polygon|paid|respond|house|round|merge|survey|date|today", names(d), ignore.case = TRUE) | grepl("transport|bribe|pot de vin", labs, ignore.case = TRUE)
  for (i in which(keep)) cat(sprintf("%s | %s\n", names(d)[i], substr(labs[i], 1, 100)))
}
cc <- read_dta(file.path(B, "survey_data/chief_consultations.dta"))
cat("\nchief consultations\n"); tb(as.vector(cc$pay_ease)); print(attr(cc$pay_ease, "labels")); tb(as.vector(cc$willingness)); print(attr(cc$willingness,"labels"))
cat("dup compound1:", sum(duplicated(cc$compound1)), " na:", sum(is.na(cc$compound1)), " nbhds:", n_distinct(cc$a7), "\n")
cc2 <- cc %>% left_join(ra, by = "a7"); tb(cc2$treatment)
cat("cc compound1 in reg:", sum(cc$compound1 %in% r2$compound1), "\n")
tb(cc$keep); tb(cc$dup_code); tb(as.vector(cc$`_merge`)); tb(cc$tot_complete_cc); tb(cc$skipped_code)
