# Exploratory: payments by arm, survey outcome coding, de facto Local nbhd (no estimates)
suppressMessages({library(haven); library(dplyr)})
options(width = 220)
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-b/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
tb <- function(...) print(table(..., useNA = "ifany"))
rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"), col_select = c(start, a7, house, compound1, exempt, collect_success))
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% select(a7, treatment, stratum) %>% mutate(treatment = as.vector(treatment))
rd <- rg %>% inner_join(ra, by = "a7") %>% mutate(house = as.vector(house)) %>% filter(house != 3) %>% arrange(compound1, start) %>% distinct(compound1, .keep_all = TRUE)
pay <- read_dta(file.path(B, "admin_data/tax_payments_noPII.dta")) %>% rename(house_pay = house)
pp <- pay %>% inner_join(rd %>% select(compound1, treatment, house), by = "compound1")
cat("payments by treatment x house\n"); tb(pp$treatment, pp$house); tb(pp$amountCF, pp$treatment)
cat("multi-payment compounds:\n"); print(pp %>% group_by(compound1) %>% filter(n() > 1) %>% select(compound1, treatment, house, amountCF, date, dup_receipt, mult_tax) %>% as.data.frame() %>% head(40))
cat("rateUSD x amountCF\n"); tb(pay$amountCF, pay$rateUSD)
# midline collector type in CXL nbhds 639, 654
ml <- read_dta(file.path(B, "survey_data/midline_noPII.dta"), col_select = c(a7, compound, col_type_fr, col_type_tsh, chef_type, visited, visits))
print(attr(ml$col_type_fr, "labels"))
x <- ml %>% inner_join(ra, by = "a7") %>% filter(treatment == 4) %>% mutate(ct = coalesce(as.vector(col_type_fr), as.vector(col_type_tsh)))
print(x %>% group_by(a7) %>% summarise(n = n(), ct1 = sum(ct == 1, na.rm=TRUE), ct2 = sum(ct == 2, na.rm=TRUE), ct3 = sum(ct == 3, na.rm=TRUE), ct0 = sum(ct == 0, na.rm=TRUE), ctNA = sum(is.na(ct))) %>% as.data.frame())
y <- ml %>% inner_join(ra, by = "a7") %>% mutate(ct = coalesce(as.vector(col_type_fr), as.vector(col_type_tsh)))
cat("col_type by arm\n"); tb(y$treatment, y$ct)
ml2 <- y %>% filter(treatment %in% c(1,2))
cat("visited x visits>1 (C/L)\n"); tb(as.vector(ml2$visited), pmin(as.vector(ml2$visits), 99))
cat("midline compound in reg:", sum(ml2$compound %in% rd$compound1), " of", nrow(ml2), " dup compound:", sum(duplicated(ml2$compound)), "\n")
# endline round1
e1 <- read_dta(file.path(B, "survey_data/endline_round1_noPII.dta"), col_select = c(a7, treatment, today, code, compound_code, bribe, bribe_amt, visited, paid_self, dup_respondent, dup_compound))
cat("\nendline1 rows", nrow(e1), "\n"); tb(as.vector(e1$bribe)); print(attr(e1$bribe, "labels")); tb(e1$dup_respondent); tb(e1$dup_compound); tb(as.vector(e1$visited))
print(summary(e1$today))
e1j <- e1 %>% inner_join(ra %>% rename(atr = treatment), by = "a7")
cat("bribe by assigned arm\n"); tb(e1j$atr, as.vector(e1j$bribe))
cat("bribe x visited\n"); tb(as.vector(e1j$visited), as.vector(e1j$bribe))
cat("bribe x paid_self\n"); tb(as.vector(e1j$paid_self), as.vector(e1j$bribe))
cat("bribe x dup_respondent\n"); tb(e1j$dup_respondent, as.vector(e1j$bribe))
cat("endline treatment vs assigned\n"); tb(e1j$atr, as.vector(e1j$treatment))
e2 <- read_dta(file.path(B, "survey_data/endline_round2_noPII.dta"), col_select = c(a7, treatment, today, code))
cat("endline2 rows", nrow(e2), "\n"); print(summary(e2$today)); cat("codes overlap r1:", sum(e2$code %in% e1$code), "\n")
# chief consultations
cc <- read_dta(file.path(B, "survey_data/chief_consultations.dta")) %>% select(a7, compound1, pay_ease, willingness)
ccr <- cc %>% inner_join(rd %>% select(compound1, treatment, house), by = "compound1")
cat("consultations merged to reg:", nrow(ccr), " pay_ease 0-2:", sum(ccr$pay_ease %in% 0:2), "\n"); tb(ccr$treatment)
