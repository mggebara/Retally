# Exploratory: dates, filters for property counts, treatment sources (no estimates)
suppressMessages({library(haven); library(dplyr)})
options(width = 220)
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-b/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
tb <- function(...) print(table(..., useNA = "ifany"))
rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"),
  col_select = c(start, end, today, today_fr, date, date_f, month_tmp_fr, day_tmpp, a7, a7b, tmt, house, compound1, compound2, exempt, tot_complete, double_sensi, dup_poly, pilot, type, a7_compound))
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% select(a7, treatment, stratum) %>% mutate(treatment = as.vector(treatment))
rs <- read_dta(file.path(B, "admin_data/randomization_schedule.dta")) %>% select(a7, month)
r <- rg %>% inner_join(ra, by = "a7") %>% left_join(rs, by = "a7") %>% filter(as.vector(house) != 3)
cat("rows with missing today: sample\n")
print(head(as.data.frame(r %>% filter(is.na(today)) %>% select(a7, start, end, today_fr, date, date_f, month_tmp_fr, day_tmpp, type)), 15))
cat("type x missing today\n"); tb(r$type, is.na(r$today))
cat("start missing:", sum(is.na(r$start)), "\n")
r <- r %>% mutate(sdate = as.Date(start))
cat("sdate vs today diff:\n"); print(summary(as.numeric(r$sdate - r$today)))
# filters
cat("compound1 != compound2:", sum(r$compound1 != r$compound2, na.rm=TRUE), " NA c2:", sum(is.na(r$compound2)), "\n")
r <- r %>% mutate(pref = floor(compound1 / 1000), pref_ok = pref == a7 | (a7 > 1000 & floor(compound1/1000) == a7))
cat("prefix != a7:\n"); tb(r$treatment, r$pref_ok)
print(head(r %>% filter(!pref_ok) %>% select(a7, a7b, compound1, compound2, a7_compound), 10))
cat("compound1 digits:\n"); tb(nchar(as.character(r$compound1)))
tb(r$treatment, r$a7 == r$a7b)
cat("by treatment: exempt\n"); tb(r$treatment, as.vector(r$exempt))
# taxroll
tr <- read_dta(file.path(B, "admin_data/taxroll_noPII.dta")) %>% select(compound1, a7, Exempte, MontantIF)
cat("\ntaxroll rows", nrow(tr), " dup:", sum(duplicated(tr$compound1)), "\n")
tr2 <- tr %>% inner_join(ra, by = "a7"); tb(tr2$treatment)
cat("taxroll in reg:", sum(tr$compound1 %in% r$compound1), " reg in taxroll:", sum(unique(r$compound1) %in% tr$compound1), "\n")
r <- r %>% mutate(in_tr = compound1 %in% tr$compound1)
cat("reg (non-villa, dedup) in taxroll by treatment:\n"); rd <- r %>% distinct(compound1, .keep_all = TRUE); tb(rd$treatment, rd$in_tr)
tb(tr$Exempte); tb(substr(tr$MontantIF, 1, 6))
# per-nbhd dates using start
nb <- r %>% group_by(a7, treatment, month) %>% summarise(n = n(), s0 = min(sdate, na.rm=TRUE), smed = median(sdate, na.rm=TRUE), s1 = max(sdate, na.rm=TRUE), nmiss = sum(is.na(sdate)), .groups = "drop")
print(nb %>% group_by(treatment, month) %>% summarise(k = n(), n = sum(n), s0min = min(s0), s0max = max(s0), s1max = max(s1), .groups="drop") %>% as.data.frame())
print(nb %>% filter(treatment %in% c(1,2,3)) %>% arrange(s0) %>% as.data.frame(), max = 5000)
# midline
ml <- read_dta(file.path(B, "survey_data/midline_noPII.dta"), col_select = c(a7, compound, today, treatment, month, tmt, visited, visits, bribe, tot_complete, pilot, dup_real, dup_compound, control, short, sample_select, first_attempt, present, exempt))
cat("\nmidline rows", nrow(ml), "\n")
for (v in c("treatment","month","tmt","visited","visits","bribe","tot_complete","pilot","dup_real","dup_compound","control","short","sample_select","first_attempt","present","exempt")) { cat("--", v, "\n"); tb(as.vector(ml[[v]])) }
print(attr(ml$visited, "labels")); print(attr(ml$bribe, "labels"))
m2 <- ml %>% inner_join(ra %>% rename(atr = treatment), by = "a7")
cat("midline treatment vs assignment\n"); tb(m2$atr, as.vector(m2$treatment))
cat("midline month vs schedule\n"); m2 <- m2 %>% left_join(rs %>% rename(smonth = month), by = "a7"); tb(m2$smonth, as.vector(m2$month))
