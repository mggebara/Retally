# Exploratory: sensitivity of col2 to the construction of the campaign-period FE (no RESULT lines)
suppressMessages({library(haven); library(dplyr); library(fixest); library(lubridate)})
options(width = 200)
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-b/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
ra <- read_dta(file.path(B, "admin_data/randomization_assignment.dta")) %>% transmute(a7, treatment = as.vector(treatment), stratum)
ra$treatment[ra$a7 == 654] <- 2
rs <- read_dta(file.path(B, "admin_data/randomization_schedule.dta")) %>% select(a7, month)
rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"), col_select = c(start, a7, house, compound1))
reg <- rg %>% inner_join(ra, by = "a7") %>% left_join(rs, by = "a7") %>% mutate(house = as.vector(house), rdate = as.Date(start)) %>%
  filter(house %in% c(1, 2)) %>% arrange(compound1, start) %>% distinct(compound1, .keep_all = TRUE)
pay <- read_dta(file.path(B, "admin_data/tax_payments_noPII.dta"))
reg$paid <- as.integer(reg$compound1 %in% pay$compound1)
d <- reg %>% filter(treatment %in% c(1, 2)) %>% mutate(local = as.integer(treatment == 2))
s <- as.Date("2018-06-19"); e <- as.Date("2018-12-11")
d <- d %>% group_by(a7) %>% mutate(nmin = min(rdate), nmed = median(rdate), nmax = max(rdate)) %>% ungroup()
w <- d %>% filter(rdate >= s & rdate <= e)
bin <- function(x, anchor, k) findInterval(as.numeric(x), as.numeric(anchor %m+% months(seq(0, 24, by = k))))
run <- function(dd, f, label) { m <- feols(f, dd, cluster = ~a7); cat(sprintf("%-40s N=%d coef=%.4f se=%.4f\n", label, nobs(m), coef(m)["local"], se(m)["local"])) }
run(w %>% mutate(p = bin(rdate, s, 2)), paid ~ local | stratum + p, "prop 2m from s")
run(w %>% mutate(p = bin(nmin, s, 2)), paid ~ local | stratum + p, "nbhd-min 2m from s")
run(w %>% mutate(p = bin(nmed, s, 2)), paid ~ local | stratum + p, "nbhd-med 2m from s")
run(w %>% mutate(p = bin(rdate, s, 1)), paid ~ local | stratum + p, "prop 1m from s")
run(w %>% mutate(p = bin(rdate, as.Date("2018-06-15"), 2)), paid ~ local | stratum + p, "prop 2m from Jun15")
run(w %>% mutate(p = month), paid ~ local | stratum + p, "schedule month FE")
run(w %>% mutate(p = month(rdate)), paid ~ local | stratum + p, "calendar month FE")
run(w %>% mutate(p = (month(rdate) - 6) %/% 2), paid ~ local | stratum + p, "calendar 2-month FE")
run(w, paid ~ local | stratum, "window, no period FE")
d2 <- d %>% filter(nmin >= s & nmin <= e)
run(d2 %>% mutate(p = bin(nmin, s, 2)), paid ~ local | stratum + p, "nbhd-min sample & bins")
d3 <- d %>% filter(nmed >= s & nmed <= e)
run(d3 %>% mutate(p = bin(nmed, s, 2)), paid ~ local | stratum + p, "nbhd-med sample & bins")
cat("periods table (prop 2m):\n"); print(table(bin(w$rdate, s, 2), w$local))
