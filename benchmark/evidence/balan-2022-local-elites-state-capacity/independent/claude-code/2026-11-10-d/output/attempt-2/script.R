f2$d <- as.Date(f2$today)
print(f2 %>% group_by(treatment.y) %>% summarise(mn = min(d, na.rm=TRUE), mx = max(d, na.rm=TRUE), q01 = quantile(d, .01, type=1, na.rm=TRUE), q99 = quantile(d, .99, type=1, na.rm=TRUE), n = n()))
