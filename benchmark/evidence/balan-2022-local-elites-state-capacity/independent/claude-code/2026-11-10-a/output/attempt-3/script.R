# neighborhood dates
rg$d <- as.Date(rg$start)
nb <- rg %>% filter(treatment %in% c(1, 2)) %>% group_by(a7, treatment, month) %>%
  summarise(n = n(), dmin = min(d), dp10 = quantile(as.numeric(d), .1), dmed = median(as.numeric(d)), dmax = max(d), .groups = "drop") %>%
  mutate(dp10 = as.Date(dp10, origin = "1970-01-01"), dmed = as.Date(dmed, origin = "1970-01-01")) %>% arrange(treatment, dmin)
print(as.data.frame(nb), row.names = FALSE)
