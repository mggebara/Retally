for (v in c("error_code", "unmatched_compound", "lateCollection", "dup_receipt", "mult_tax", "rate_verified", "Villas", "Maison_Moyenne", "house", "paid", "error_rate")) { cat(v, ":\n"); print(table(tp[[v]], useNA = "ifany")) }
print(summary(tp$amountCF)); print(table(tp$amountCF, useNA = "ifany"))
cat("payments compound in reg (c5):", sum(tp$compound1 %in% c5$compound1), "\n")
print(table(tp$date > as.Date("2018-12-31"), useNA = "ifany")); print(range(tp$date, na.rm = TRUE))
