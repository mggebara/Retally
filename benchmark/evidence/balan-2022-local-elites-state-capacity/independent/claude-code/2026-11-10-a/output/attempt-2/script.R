# Exploratory 2: registration cleaning, treatment/month, payment merge (no estimates)
suppressMessages({library(haven); library(dplyr)})
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/independent/2026-11-10-a/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
ra <- zap_labels(read_dta(file.path(B, "admin_data/randomization_assignment.dta")))
rs <- zap_labels(read_dta(file.path(B, "admin_data/randomization_schedule.dta")))
cat("assignment treatment\n"); print(table(ra$treatment))
cat("schedule treatment\n"); print(table(rs$treatment))
m <- merge(ra[, c("a7", "treatment", "stratum")], rs[, c("a7", "treatment", "month")], by = "a7", suffixes = c(".ra", ".rs"))
print(table(m$treatment.ra, m$treatment.rs))
print(table(m$treatment.rs, m$month))
st <- zap_labels(read_dta(file.path(B, "admin_data/stratum.dta")))
mm <- merge(ra[, c("a7", "stratum")], st[, c("a7", "stratum")], by = "a7")
cat("stratum ra vs stratum.dta identical partition? ", length(unique(paste(mm$stratum.x, mm$stratum.y))), "\n")

rg <- read_dta(file.path(B, "admin_data/registration_noPII.dta"))
rg <- zap_labels(rg)
cat("\nregistration rows", nrow(rg), "\n")
for (v in c("pilot", "dup_poly", "carto_pay", "tot_complete", "double_sensi", "house", "first", "tmt", "who", "exempt", "exempt_enum", "correct", "chalk_check")) {
  cat(v, ":\n"); print(table(rg[[v]], useNA = "ifany"))
}
cat("a7 in assignment:", sum(rg$a7 %in% ra$a7), "\n")
cat("a7 == a7_compound:", sum(rg$a7 == rg$a7_compound), " compound1==compound2:", sum(rg$compound1 == rg$compound2), "\n")
cat("dup compound1:", sum(duplicated(rg$compound1)), "\n")
cat("floor(compound1/1000)==a7:", sum(floor(rg$compound1 / 1000) == rg$a7), "\n")
rg2 <- rg %>% left_join(rs[, c("a7", "treatment", "month")], by = "a7")
cat("treatment x pilot\n"); print(table(rg2$treatment, rg2$pilot, useNA = "ifany"))
cat("treatment x tmt\n"); print(table(rg2$treatment, rg2$tmt, useNA = "ifany"))
f <- function(d) { d %>% group_by(treatment) %>% summarise(n = n(), nhood = n_distinct(a7)) %>% as.data.frame() }
cat("all\n"); print(f(rg2))
c1 <- rg2 %>% filter(pilot == 0)
cat("pilot==0\n"); print(f(c1))
c2 <- c1 %>% filter(is.na(carto_pay) | carto_pay == 0)
cat("+carto_pay!=1\n"); print(f(c2))
c3 <- c2 %>% filter(tot_complete == 1)
cat("+tot_complete\n"); print(f(c3))
c4 <- c3 %>% filter(house %in% c(1, 2))
cat("+house 1/2\n"); print(f(c4))
c5 <- c4 %>% distinct(compound1, .keep_all = TRUE)
cat("+distinct compound\n"); print(f(c5))
c6 <- c2 %>% filter(house %in% c(1, 2)) %>% distinct(compound1, .keep_all = TRUE)
cat("pilot0,carto0,house12,distinct (no tot_complete)\n"); print(f(c6))
c7 <- c2 %>% filter(house %in% c(1, 2), is.na(dup_poly) | dup_poly == 0) %>% distinct(compound1, .keep_all = TRUE)
cat("+dup_poly0\n"); print(f(c7))
# month and dates by treatment
cat("\nregistration dates by treatment x month\n")
print(as.data.frame(c5 %>% group_by(treatment, month) %>% summarise(n = n(), nh = n_distinct(a7), dmin = min(today, na.rm = TRUE), dmed = median(today, na.rm = TRUE), dmax = max(today, na.rm = TRUE), .groups = "drop")))
nb <- c5 %>% group_by(a7, treatment, month) %>% summarise(n = n(), dmin = min(today, na.rm = TRUE), dmed = median(today, na.rm = TRUE), dmax = max(today, na.rm = TRUE), .groups = "drop")
cat("treatment first/last nb registration dates\n")
print(as.data.frame(nb %>% group_by(treatment) %>% summarise(first = min(dmin), last = max(dmax), firstmed = min(dmed), lastmed = max(dmed))))

