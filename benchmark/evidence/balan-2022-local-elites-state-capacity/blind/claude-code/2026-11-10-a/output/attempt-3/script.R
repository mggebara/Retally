suppressMessages({library(haven); library(dplyr)})
B <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/blind/2026-11-10-a/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
rd <- function(p, ...) read_dta(file.path(B, p), ...)
sch <- rd("admin_data/randomization_schedule.dta") %>% select(a7, treatment, month)
asg <- rd("admin_data/randomization_assignment.dta") %>% transmute(a7, tr_asg = as.numeric(treatment), stratum)
sch <- left_join(sch, asg, by = "a7")
cat("schedule vs assignment treatment\n"); print(table(sch$treatment, sch$tr_asg))
cat("month by treatment\n"); print(table(sch$treatment, sch$month))

reg <- rd("admin_data/registration_noPII.dta", col_select = c(a7, a7b, a7_compound, compound1, compound2, today, start, house, who, tmt, exempt, carto_pay))
reg$day <- as.Date(ifelse(is.na(reg$today), as.Date(reg$start), reg$today), origin = "1970-01-01")
cat("a7 vs a7_compound equal:", mean(reg$a7 == reg$a7_compound), " compound1 floor/1000 == a7_compound:", mean(floor(reg$compound1/1000) == reg$a7_compound), "\n")
cat("dup compound1:", sum(duplicated(reg$compound1)), "\n")
cat("tmt by schedule treatment (via a7_compound)\n")
r2 <- left_join(reg, sch, by = c("a7_compound" = "a7"))
print(table(r2$tmt, r2$treatment, useNA = "ifany"))
cat("who by schedule treatment\n"); print(table(as_factor(r2$who), r2$treatment, useNA = "ifany"))
cx <- r2 %>% filter(treatment == 4) %>% group_by(a7_compound) %>% summarise(n = n(), chef = mean(who == 1, na.rm = TRUE), both = mean(who == 2, na.rm = TRUE), agent = mean(who == 0, na.rm=TRUE), tmt = paste(unique(tmt), collapse=","))
print(as.data.frame(cx %>% arrange(both)), digits = 3)
cat("rows with a7_compound not in schedule:", sum(is.na(r2$treatment)), " unique a7:", paste(unique(r2$a7_compound[is.na(r2$treatment)]), collapse=","), "\n")
nb <- r2 %>% filter(!is.na(treatment)) %>% group_by(a7_compound, treatment, month) %>%
  summarise(n = n(), d0 = min(day, na.rm=TRUE), dmed = median(day, na.rm=TRUE), d1 = max(day, na.rm=TRUE), .groups = "drop")
cat("neighborhood registration dates by treatment\n")
print(nb %>% group_by(treatment) %>% summarise(n_nb = n(), first_d0 = min(d0), last_d0 = max(d0), first_med = min(dmed), last_med = max(dmed), last_d1 = max(d1)))
print(nb %>% group_by(treatment, month) %>% summarise(n = n(), d0min = min(d0), d0max = max(d0), .groups="drop") %>% as.data.frame())

tr <- rd("admin_data/taxroll_noPII.dta")
cat("taxroll a7 == floor(compound1/1000):", mean(tr$a7 == floor(tr$compound1/1000)), "\n")
cat("taxroll in registration:", mean(tr$compound1 %in% reg$compound1), " reg in taxroll:", mean(reg$compound1 %in% tr$compound1), "\n")
tr2 <- left_join(tr, sch, by = "a7")
print(table(tr2$treatment, useNA = "ifany"))
regh <- reg %>% group_by(compound1) %>% summarise(house = first(house), nh = n_distinct(house), exempt = max(exempt, na.rm = TRUE))
cat("compounds with multiple house types:", sum(regh$nh > 1), "\n")
tr2 <- left_join(tr2, regh, by = "compound1")
print(table(tr2$treatment, tr2$house, useNA = "ifany"))
cat("Exempte nonblank vs reg exempt\n"); print(table(tr2$Exempte != "", tr2$exempt, useNA = "ifany"))
cat("DatePaye nonblank by treatment\n"); print(table(tr2$DatePaye != "", tr2$treatment, useNA="ifany"))

