cat("pay compound in taxroll:", mean(pay$compound1 %in% tr$compound1), "\n")
print(table(error_code = pay$error_code, intaxroll = pay$compound1 %in% tr$compound1, useNA = "ifany"))
print(table(unmatched = pay$unmatched_compound, intaxroll = pay$compound1 %in% tr$compound1, useNA = "ifany"))
cat("pay a7 == floor(compound1/1000):", mean(pay$a7 == floor(pay$compound1/1000), na.rm=TRUE), " a7==polygon:", mean(pay$a7==pay$polygon, na.rm=TRUE), "\n")
print(summary(pay$date)); print(table(pay$lateCollection, useNA="ifany"))
print(table(pay$amountCF, pay$house, useNA = "ifany"))
dups <- pay %>% filter(!is.na(compound1)) %>% group_by(compound1) %>% filter(n() > 1) %>% arrange(compound1)
print(as.data.frame(head(dups %>% select(compound1, amountCF, date, error_code, a7, dup_receipt, mult_tax, unmatched_compound), 30)))
