suppressPackageStartupMessages({library(haven); library(dplyr)})
base <- "<repo>/benchmark/.cache/claude-code/balan-2022-local-elites-state-capacity/blind/2026-11-10-d/mount/balan_2022_local_elites_state_capacity/Replication Materials - Updated October 2025/Data/01_base"
rd <- function(f, ...) read_dta(file.path(base, f), ...)
tb <- function(...) print(table(..., useNA = "ifany"))
ra <- rd("admin_data/randomization_assignment.dta") %>% mutate(treatment = as.numeric(zap_labels(treatment)))
tpn <- rd("admin_data/tax_payments_neighborhoods.dta")
x <- left_join(ra %>% select(a7, stratum, treatment), tpn %>% select(a7, s3 = stratum, program, nganza, non_residential), by = "a7")
cat("ra stratum == tpn stratum:", mean(x$stratum == x$s3), "\n"); tb(x$program, x$treatment); tb(x$non_residential, x$treatment)
cat("tpn rows", nrow(tpn), "\n")

reg <- rd("admin_data/registration_noPII.dta")
reg <- reg %>% mutate(across(where(is.labelled), ~as.numeric(zap_labels(.x)))) %>%
  left_join(ra %>% select(a7, treatment, stratum), by = "a7")
cat("reg a7 not in ra:", sum(is.na(reg$treatment)), " pilot among them:", sum(is.na(reg$treatment) & reg$pilot == 1), "\n")
tb(is.na(reg$treatment), reg$pilot)
tb(reg$treatment, is.na(reg$carto_pay))
f <- reg %>% filter(!is.na(treatment), pilot == 0)
tb(f$treatment, f$house)
f2 <- f %>% filter(tot_complete == 1, house != 3)
cat("after tot_complete, nonvilla:\n"); tb(f2$treatment)
f3 <- f2 %>% distinct(compound1, .keep_all = TRUE); cat("dedup compound:\n"); tb(f3$treatment)
f4 <- f3 %>% filter(double_sensi == 0); tb(f4$treatment)
# who by neighborhood
w <- f %>% group_by(a7, treatment) %>% summarise(n = n(), chef = mean(who == 1, na.rm = TRUE), agent = mean(who == 0, na.rm = TRUE), both = mean(who == 2, na.rm=TRUE), tmt2 = mean(tmt == 2, na.rm=TRUE), tmt4 = mean(tmt==4, na.rm=TRUE), .groups = "drop")
print(as.data.frame(w %>% filter(treatment == 4) %>% arrange(desc(chef))) %>% head(8))
print(as.data.frame(w %>% filter(treatment == 2) %>% arrange(chef)) %>% head(5))
# dates
f <- f %>% mutate(d = as.Date(start), d2 = today)
cat("start NA", sum(is.na(f$d)), " today NA", sum(is.na(f$d2)), " agree", mean(f$d == f$d2, na.rm=TRUE), "\n")
nd <- f %>% group_by(a7, treatment) %>% summarise(dmin = min(d, na.rm=TRUE), dmed = median(d, na.rm=TRUE), dmax = max(d, na.rm=TRUE), n = n(), .groups="drop")
print(nd %>% group_by(treatment) %>% summarise(first = min(dmin), last = max(dmin), firstmed = min(dmed), lastmed = max(dmed), lastmax = max(dmax)))
rs <- rd("admin_data/randomization_schedule.dta")
nd <- left_join(nd, rs %>% select(a7, month), by = "a7")
print(as.data.frame(nd %>% group_by(month) %>% summarise(min = min(dmin), q10 = quantile(dmin, .1, type=1), med = median(dmin), q90 = quantile(dmin, .9, type=1), max = max(dmin), n = n())))
print(as.data.frame(nd %>% filter(treatment %in% c(1,2)) %>% arrange(dmin) %>% select(a7, treatment, month, dmin, dmed, dmax, n) %>% head(15)))
print(as.data.frame(nd %>% filter(treatment %in% c(1,2)) %>% arrange(desc(dmin)) %>% select(a7, treatment, month, dmin, dmed, dmax, n) %>% head(15)))

