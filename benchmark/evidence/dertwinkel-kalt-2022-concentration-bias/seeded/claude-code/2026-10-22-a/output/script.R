suppressPackageStartupMessages({library(readr); library(dplyr); library(fixest); library(AER)})
set.seed(42)
f <- "<repo>/benchmark/.cache/claude-code/dertwinkel-kalt-2022-concentration-bias/seeded/2026-10-22-a/mount/dertwinkel_kalt_2022_concentration_bias/Consumption Experiment/Stata/Consumption_Experiment.csv"
d <- read_csv(f, show_col_types = FALSE, guess_max = 10000)

# Table 2: Main-Treatment, PAP sample (Stata drops rows with missing outcome -> one row per subject)
t2 <- d %>% filter(pap_sample == 1, dispersed == 0, treatment == 1)
m_mid  <- feols(avg_id_stage2 ~ 1, data = t2, vcov = "hetero")
m_rl   <- feols(qe_ard_lower ~ 1, data = t2, vcov = "hetero")
m_rm   <- feols(qe_ard ~ 1, data = t2, vcov = "hetero")
m_ru   <- feols(qe_ard_upper ~ 1, data = t2, vcov = "hetero")
t2t <- t2 %>% filter(!is.na(id_stage2))
m_tob  <- tobit(id_stage2 ~ 1, left = -63, right = 63, data = t2t)
print(summary(m_tob))

# Table 3
c1 <- feols(qe_ard ~ main, data = d %>% filter(pap_sample == 1, treatment == 1), vcov = "hetero")
c2 <- feols(qe_ard ~ control, data = d %>% filter(pap_sample == 1, pizza == 0), vcov = "hetero")
c3 <- feols(qe_ard ~ treatment, data = d %>% filter(pap_sample == 1, pizza == 1, dispersed == 0), vcov = "hetero")
c4 <- feols(qe_ard ~ treatment, data = d %>% filter(pap_sample == 1, pizza == 1, dispersed == 1), vcov = "hetero")
print(etable(m_mid, m_rl, m_rm, m_ru))
print(etable(c1, c2, c3, c4))

r <- function(n, v) cat(sprintf("RESULT:%s=%.6f\n", n, v))
r("abs_concentration_bias_midpoint_table2_col2", coef(m_mid)[1])
r("abs_concentration_bias_tobit_table2_col4", coef(m_tob)[1])
r("rel_concentration_bias_lower_table2_col1", coef(m_rl)[1])
r("rel_concentration_bias_midpoint_table2_col2", coef(m_rm)[1])
r("rel_concentration_bias_upper_table2_col3", coef(m_ru)[1])
r("n_obs_table2", nobs(m_rm))
r("rel_cb_mechanism_treatment_table3_col1", coef(c1)[["(Intercept)"]])
r("diff_main_minus_mechanism_table3_col1", coef(c1)[["main"]])
# Donation-Treatment = control==0 -> intercept; diff Treatment - Control = -coef(control)
r("rel_cb_donation_treatment_table3_col2", coef(c2)[["(Intercept)"]])
r("diff_donation_treatment_minus_control_table3_col2", -coef(c2)[["control"]])
r("diff_main_treatment_minus_control_table3_col3", coef(c3)[["treatment"]])
r("diff_mechanism_treatment_minus_control_table3_col4", coef(c4)[["treatment"]])
r("n_obs_table3", nobs(c1))
cat(sprintf("Table3 nobs: %d %d %d %d\n", nobs(c1), nobs(c2), nobs(c3), nobs(c4)))
