suppressMessages(library(tidyverse))
f <- "<repo>/benchmark/.cache/claude-code/dertwinkel-kalt-2022-concentration-bias/blind/2026-11-02-c/mount/dertwinkel_kalt_2022_concentration_bias/Consumption Experiment/Stata/Consumption_Experiment.csv"
d <- read_csv(f, show_col_types = FALSE)
e <- c(129,132,143,115,121,117,135,127)
bal <- d %>% filter(decision_number <= 8)
fin <- d %>% filter(decision_number == 9)
cb <- bal %>% group_by(tn) %>% summarise(any_corner = any(corner != 0), maxip = max(indifference_point), minip = min(indifference_point))
xw <- bal %>% select(tn, utility_point, indifference_point) %>% arrange(tn, utility_point) %>% pivot_wider(names_from = utility_point, values_from = indifference_point, names_prefix = "x")
s <- fin %>% left_join(cb, by = "tn") %>% left_join(xw, by = "tn")
print(s %>% filter(!any_corner, pap_sample == 0) %>% select(tn, session, dispersed, pizza, control, corner, indifference_point, maxip, minip, average_ip, id_stage2) %>% as.data.frame())
print(s %>% count(session, pap_sample) %>% pivot_wider(names_from = pap_sample, values_from = n) %>% as.data.frame())
X <- as.matrix(s[, paste0("x", 1:8)])
den <- sweep(X, 2, e, "+")
s$avgx <- rowMeans(X)
s$r1 <- s$avg_id_stage2 * rowMeans(1/den)
s$r2 <- s$avg_id_stage2 / (mean(e) + s$avgx)
s$r3 <- rowMeans(s$avg_id_stage2 / (sweep(X, 2, e, "+") + s$avg_id_stage2))
p <- s %>% filter(pap_sample == 1)
p %>% group_by(control) %>% summarise(across(c(r1, r2, r3), ~ max(abs(.x - qe_rad))), ard = max(abs(r2 - qe_ard)), xdiff = max(abs(avgx - average_ip))) %>% print()
p %>% mutate(dd = r1 - qe_rad) %>% arrange(desc(abs(dd))) %>% select(tn, control, corner, avg_id_stage2, avgx, average_ip, r1, qe_rad, qe_ard, dd) %>% head(8) %>% as.data.frame() %>% print()
print(head(as.data.frame(p %>% select(tn, x1:x8, avg_id_stage2, qe_rad, r1)), 5))
