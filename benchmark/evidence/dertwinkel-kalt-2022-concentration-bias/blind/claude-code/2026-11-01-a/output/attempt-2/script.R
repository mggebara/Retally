suppressMessages(library(tidyverse))
options(width = 250)
p <- "<repo>/benchmark/.cache/claude-code/dertwinkel-kalt-2022-concentration-bias/blind/2026-11-01-a/mount/dertwinkel_kalt_2022_concentration_bias/Consumption Experiment/Stata/Consumption_Experiment.csv"
d <- read_csv(p, show_col_types = FALSE)
bal <- d %>% filter(decision_number <= 8)
fin <- d %>% filter(decision_number == 9)
cat("balanced: corner x ip range\n"); print(bal %>% group_by(corner) %>% summarise(n = n(), mn = min(indifference_point), mx = max(indifference_point)))
cat("balanced: utility_point unique per subject?\n"); print(table(bal %>% group_by(tn) %>% summarise(k = n_distinct(utility_point)) %>% pull(k)))
cat("final: corner x ip\n"); print(fin %>% group_by(corner) %>% summarise(n = n(), mn = min(indifference_point), mx = max(indifference_point),
  up_mn = min(id_stage2_upper, na.rm=TRUE), up_mx = max(id_stage2_upper, na.rm=TRUE), na_up = sum(is.na(id_stage2_upper))))
cat("final upper corners rows\n"); print(as.data.frame(fin %>% filter(corner == 1) %>% select(tn, treatment, pizza, main, indifference_point, id_stage2_upper, id_stage2, avg_id_stage2, pap_sample) %>% head(40)))
cat("final lower corners rows\n"); print(as.data.frame(fin %>% filter(corner == -1) %>% select(tn, treatment, pizza, main, indifference_point, id_stage2_upper, id_stage2, avg_id_stage2, pap_sample)))
anyc <- bal %>% group_by(tn) %>% summarise(any_corner = any(corner != 0), cc = first(na.omit(chose_corner)))
cat("any balanced corner vs chose_corner\n"); print(table(anyc$any_corner, anyc$cc, useNA = "ifany"))
s <- fin %>% left_join(anyc, by = "tn")
cat("any corner vs pap_sample\n"); print(table(s$any_corner, s$pap_sample, useNA = "ifany"))
s <- s %>% mutate(cond = case_when(pizza == 0 ~ "Donation", main == 1 ~ "Main", TRUE ~ "Mechanism"), arm = ifelse(treatment == 1, "Treatment", "Control"))
print(s %>% count(cond, arm, any_corner))
cat("rows with chose_corner non-NA: decision numbers\n"); print(table(d$decision_number[!is.na(d$chose_corner)]))
cat("final utility_point by arm\n"); print(table(s$arm, s$utility_point))
cat("final ip in control: range\n"); print(summary(s$indifference_point[s$arm=="Control"]))
cat("session by cond\n"); print(table(s$session, s$cond))
