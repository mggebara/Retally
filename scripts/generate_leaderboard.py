"""Aggregate validation reports into a per-author reproducibility leaderboard.

Reads ``docs/data/reports.json`` and emits two artefacts:

* ``LEADERBOARD.md`` at the repo root — markdown table, browsable on GitHub.
* ``docs/data/leaderboard.json`` — same data structured as JSON so the
  dashboard (or any downstream tool) can consume it without re-running
  the aggregation.

Every author named on a paper is credited; a 3-author paper contributes
one row to each of those three authors.  Authors are ranked by claim
pass rate descending, then by total claims descending, then alphabetically.

Re-run after editing reports.json with::

    make leaderboard
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
REPORTS_FILE = REPO_ROOT / "docs" / "data" / "reports.json"
LEADERBOARD_JSON = REPO_ROOT / "docs" / "data" / "leaderboard.json"
LEADERBOARD_MD = REPO_ROOT / "LEADERBOARD.md"


@dataclass
class AuthorStats:
    author: str
    papers: int = 0
    papers_passed: int = 0
    claims: int = 0
    claims_validated: int = 0
    claims_unvalidatable: int = 0
    """Claims where the pipeline could not produce a reproduced value at all
    (execution crash, missing dataset, unmatched output).  A subset of
    ``claims - claims_validated``."""

    @property
    def claim_pass_rate(self) -> float:
        return self.claims_validated / self.claims if self.claims else 0.0

    @property
    def paper_pass_rate(self) -> float:
        return self.papers_passed / self.papers if self.papers else 0.0


def build_leaderboard(reports: list[dict]) -> list[AuthorStats]:
    """Return one ``AuthorStats`` per distinct author across all reports.

    The ranking is stable: ties on claim pass rate fall back to total
    claims then to author name, so re-running on unchanged data produces
    byte-identical output (important for clean diffs).
    """
    stats: dict[str, AuthorStats] = {}
    for r in reports:
        authors = r["paper"].get("authors", [])
        claim_results = r.get("claim_results", [])
        n_claims = len(claim_results)
        n_passed = sum(1 for c in claim_results if c.get("passed"))
        n_unvalidatable = sum(
            1 for c in claim_results if c.get("reproduced_value") is None
        )
        overall_passed = bool(r.get("overall_passed"))

        for author in authors:
            s = stats.setdefault(author, AuthorStats(author=author))
            s.papers += 1
            s.claims += n_claims
            s.claims_validated += n_passed
            s.claims_unvalidatable += n_unvalidatable
            if overall_passed:
                s.papers_passed += 1

    return sorted(
        stats.values(),
        key=lambda s: (-s.claim_pass_rate, -s.claims, s.author),
    )


def write_json(stats: list[AuthorStats]) -> None:
    rows = [
        {
            "author": s.author,
            "papers": s.papers,
            "papers_passed": s.papers_passed,
            "claims": s.claims,
            "claims_validated": s.claims_validated,
            "claims_unvalidatable": s.claims_unvalidatable,
            "claim_pass_rate": round(s.claim_pass_rate, 4),
            "paper_pass_rate": round(s.paper_pass_rate, 4),
        }
        for s in stats
    ]
    LEADERBOARD_JSON.write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")


def write_markdown(stats: list[AuthorStats], n_reports: int) -> None:
    lines = [
        "# OpenRA Reproducibility Leaderboard",
        "",
        f"Tracks how each author's papers fare when OpenRA tries to reproduce ",
        "their published quantitative claims.  Every named co-author is credited, ",
        "so a 3-author paper contributes one row to each of those three authors.",
        "",
        f"Source: `docs/data/reports.json` ({n_reports} reports).  ",
        "Auto-generated by `scripts/generate_leaderboard.py` — run `make leaderboard` ",
        "after adding or updating reports.",
        "",
        "Ranking is by claim pass rate, with ties broken by total claims then by ",
        "author name.  A claim is *unvalidatable* when the pipeline could not ",
        "produce a reproduced value at all (execution crash, missing dataset, or ",
        "no captured output matching the claim).",
        "",
        "| # | Author | Papers | Papers passed | Claims | Validated | Unvalidatable | Pass rate |",
        "|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for i, s in enumerate(stats, 1):
        lines.append(
            f"| {i} | {s.author} | {s.papers} | {s.papers_passed} | "
            f"{s.claims} | {s.claims_validated} | {s.claims_unvalidatable} | "
            f"{s.claim_pass_rate * 100:.1f}% |"
        )
    lines.append("")
    LEADERBOARD_MD.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    reports = json.loads(REPORTS_FILE.read_text(encoding="utf-8"))
    stats = build_leaderboard(reports)
    write_json(stats)
    write_markdown(stats, n_reports=len(reports))
    print(f"Wrote {LEADERBOARD_JSON.relative_to(REPO_ROOT)} ({len(stats)} authors)")
    print(f"Wrote {LEADERBOARD_MD.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
